export function getWalkTips({ distanceMeters, durationMs, calories, weightKg }) {
  const tips = [];
  const km = distanceMeters / 1000;
  const minutes = durationMs / (1000 * 60);
  const weight = Number(weightKg) || 5;

  if (km < 0.3) {
    tips.push('Кратка разходка — следващия път опитайте още малко обиколка около квартала.');
  } else if (km < 1.5) {
    tips.push('Хубаво начало! За малко пуделче 1–2 км е чудесна ежедневна доза.');
  } else if (km < 4) {
    tips.push('Супер разстояние! Рея със сигурност е била щастлива навън.');
  } else {
    tips.push('Дълга разходка за малко кученце! Уверете се, че има вода и почивки.');
  }

  if (minutes >= 45) {
    tips.push('След по-дълга разходка дайте на пуделчето спокойно време да си отдъхне вкъщи.');
  } else if (minutes < 10 && km > 0.2) {
    tips.push('Кратко, но енергично! Добре е да редувате кратки и по-дълги разходки.');
  }

  if (calories > weight * 2) {
    tips.push('Изгорените калории са солидни — малко лакомство след игра е заслужено.');
  } else if (calories > 0) {
    tips.push(
      'Калориите са приблизителни. Ако Рея е много енергична, добавете и малко игра с топка.'
    );
  }

  if (weight < 10) {
    tips.push(
      'Малките пуделчета се уморяват и прегряват по-бързо — следете за задъхване и предлагайте вода.'
    );
  } else if (weight > 30) {
    tips.push('По-големите кучета обичат пространството — паркове и по-дълги маршрути са идеални.');
  }

  tips.push('След разходка проверете лапите за камъчета, стъкла или горещ асфалт.');
  tips.push('Редовните разходки намаляват стреса и укрепват връзката ви с Рея.');

  return tips.slice(0, 4);
}

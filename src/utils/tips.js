export function getWalkTips({ distanceMeters, durationMs, calories, weightKg }) {
  const tips = [];
  const km = distanceMeters / 1000;
  const minutes = durationMs / (1000 * 60);
  const weight = Number(weightKg) || 15;

  if (km < 0.3) {
    tips.push('Кратка разходка — следващия път опитайте още малко обиколка около квартала.');
  } else if (km < 1.5) {
    tips.push('Хубаво начало! Средна разходка около 1–2 км е чудесна за ежедневието.');
  } else if (km < 4) {
    tips.push('Супер разстояние! Кучето ви със сигурност е било щастливо навън.');
  } else {
    tips.push('Дълга разходка! Уверете се, че има достатъчно вода и почивки.');
  }

  if (minutes >= 45) {
    tips.push('След по-дълга разходка дайте на кучето спокойно време да си отдъхне вкъщи.');
  } else if (minutes < 10 && km > 0.2) {
    tips.push('Кратко, но енергично! Добре е да редувате кратки и по-дълги разходки.');
  }

  if (calories > weight * 2) {
    tips.push('Изгорените калории са солидни — може да добавите малко допълнително лакомство след игра.');
  } else if (calories > 0) {
    tips.push('Калориите са приблизителни. Ако кучето е много енергично, добавете и малко игра с топка.');
  }

  if (weight < 10) {
    tips.push('Малките кучета се уморяват по-бързо — следете за задъхване и предлагайте вода.');
  } else if (weight > 30) {
    tips.push('По-големите кучета обичат пространството — паркове и по-дълги маршрути са идеални.');
  }

  tips.push('След разходка проверете лапите за камъчета, стъкла или горещ асфалт.');
  tips.push('Редовните разходки намаляват стреса и укрепват връзката ви с кучето.');

  return tips.slice(0, 4);
}
